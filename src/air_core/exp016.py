@dataclass(frozen=True)
class StructuralMetadata016:
    module: str
    callable: str
    signature: str
    input_type: str
    output_type: str
    allowed_imports: tuple[str, ...]
    allowed_calls: tuple[str, ...]
    deterministic: bool
    side_effects: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class Evidence016:
    doc_id: str
    quote_or_span: str

    def to_dict(self) -> dict[str, str]:
        return asdict(self)


@dataclass(frozen=True)
class CanonicalContract016:
    schema_version: str
    state: str
    structural: StructuralMetadata016
    semantic: dict[str, Any]
    evidence: dict[str, Evidence016 | None]
    unknown_fields: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "state": self.state,
            "structural": self.structural.to_dict(),
            "semantic": self.semantic,
            "evidence": {key: (value.to_dict() if value else None) for key, value in self.evidence.items()},
            "unknown_fields": list(self.unknown_fields),
        }


def canonical_json_016(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _parse_model_json_016(text: str) -> dict[str, Any] | None:
    """Prefer the complete object; the legacy parser returns nested last objects."""
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?\s*", "", stripped, count=1, flags=re.I)
        stripped = re.sub(r"\s*```$", "", stripped, count=1)
    try:
        value = json.loads(stripped)
    except json.JSONDecodeError:
        value = None
        decoder = json.JSONDecoder()
        for index, character in enumerate(stripped):
            if character != "{":
                continue
            try:
                candidate, _ = decoder.raw_decode(stripped[index:])
            except json.JSONDecodeError:
                continue
            if isinstance(candidate, dict):
                value = candidate
                break
        if value is None:
            value = parse_response(text)
    return value if isinstance(value, dict) else None


