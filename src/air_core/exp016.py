def _safe_model_json_016(client: Any, store: ExperimentStore, ledger: ModelLedger015, *, kind: str,
                         prompt: str, max_tokens: int, seed: int, arm: str,
                         prompt_version: str, prompt_sha256: str, metadata: Mapping[str, Any] | None = None) -> tuple[dict[str, Any] | None, dict[str, Any]]:
    started = time.perf_counter()
    try:
        completion = client.chat_json(prompt, max_tokens=max_tokens, seed=seed)
        payload = _parse_model_json_016(completion.text)
        elapsed = completion.elapsed_seconds
        prompt_tokens = completion.prompt_tokens or 0
        generated_tokens = completion.generated_tokens or 0
        error = None
        response = completion.text
    except ModelUnavailable as exc:
        payload = None
        elapsed = getattr(client, "timeout_seconds", time.perf_counter() - started)
        prompt_tokens = generated_tokens = 0
        error = str(exc)
        response = json.dumps({"runtime_error": error})
    ledger.observe(prompt=prompt, elapsed=elapsed, prompt_tokens=prompt_tokens,
                   output_tokens=generated_tokens, timeout=error is not None, arm=arm)
    store.record_run(kind=kind, prompt=prompt, response=response, elapsed_seconds=elapsed,
                     prompt_tokens=prompt_tokens, generated_tokens=generated_tokens, passed=None,
                     metadata={**dict(metadata or {}), "arm": arm, "prompt_version": prompt_version,
                               "prompt_sha256": prompt_sha256, "runtime_error": error, "seed": seed})
    return (payload if isinstance(payload, dict) else None), {
        "elapsed_seconds": elapsed, "prompt_tokens": prompt_tokens,
        "generated_tokens": generated_tokens, "runtime_error": error,
    }


def _field_value(payload: Mapping[str, Any] | None, field_name: str) -> Any:
    if not isinstance(payload, Mapping):
        return None
    if field_name in payload:
        return payload[field_name]
    if payload.get("field") == field_name:
        return payload.get("value")
    if "value" in payload and len(payload) <= 3:
        return payload.get("value")
    return None


def _evidence_value(payload: Mapping[str, Any] | None) -> Evidence016 | None:
    if not isinstance(payload, Mapping) or not isinstance(payload.get("evidence"), Mapping):
        return None
    item = payload["evidence"]
    doc_id = item.get("doc_id") if isinstance(item.get("doc_id"), str) else None
    quote = item.get("quote_or_span") if isinstance(item.get("quote_or_span"), str) else None
    return Evidence016(doc_id, quote) if doc_id is not None and quote is not None else None


def _flatten_text(value: Any) -> str:
    if isinstance(value, str):
        return value.lower()
    if isinstance(value, Mapping):
        return " ".join(f"{key} {item}" for key, item in value.items()).lower()
    if isinstance(value, (list, tuple)):
        return " ".join(_flatten_text(item) for item in value)
    return str(value).lower()


def _semantic_required_tokens_016(family: PythonFamily009, field_name: str) -> tuple[str, ...]:
    kind, _ = _family_kind_variant_016(family)
    if field_name == "operation_summary":
        by_kind = {
            "shards": ("split", "reverse", "uppercase", "join"),
            "numbers": ("integer", "map", "deduplicate", "sort", "semicolon"),
            "object": ("json", "key", "join"),
            "mixed": ("hash", "rotate", "reverse", "append"),
            "runs": ("run", "length", "consecutive", "join"),
        }
        # The semantic summary describes behavior; the opaque callable name is
        # checked separately by the structural contract and invariant fields.
        return by_kind[kind]
    if field_name == "preconditions":
        return ("string",)
    if field_name == "postconditions":
        return ("string", "deterministic")
    if field_name == "semantic_invariants":
        return ("operation", kind)
    if field_name == "ordering_constraints":
        by_kind = {
            "shards": ("reverse", "delimiter"),
            "numbers": ("deduplicate", "sort"),
            "object": ("key",),
            "mixed": ("split", "rotate"),
            "runs": ("order",),
        }
        return by_kind[kind]
    if field_name == "special_cases":
        by_kind = {
            "shards": ("empty", "shard"),
            "numbers": ("whitespace", "integer"),
            "object": ("json", "value"),
            "mixed": ("numeric", "transformed"),
            "runs": ("empty", "input"),
        }
        return by_kind[kind]
    return ("invalid",) if field_name == "failure_behavior" else ("unknown",)


def semantic_field_correct_016(family: PythonFamily009, field_name: str, value: Any) -> bool:
    """Verify structured meaning without demanding one prose string."""
    if value is None or (isinstance(value, str) and value.strip().lower() == "unknown"):
        return False
    if isinstance(value, list) and any(str(item).strip().lower() == "unknown" for item in value):
        return False
    text = _flatten_text(value)
    tokens = _semantic_required_tokens_016(family, field_name)
    # Failure behavior is documented as a conservative constraint, not a verbatim phrase.
    if field_name == "failure_behavior":
        return any(word in text for word in ("invalid", "undocumented", "error", "not silently"))
    return all(token in text for token in tokens)


def _structural_field_value_016(structural: StructuralMetadata016, field_name: str) -> Any:
    if field_name == "allowed_calls":
        return list(structural.allowed_calls)
    if field_name == "allowed_imports":
        return list(structural.allowed_imports)
    return getattr(structural, field_name)


def _legacy_semantic_payload_016(payload: Mapping[str, Any] | None) -> dict[str, Any]:
    if not isinstance(payload, Mapping):
        return {}
    result: dict[str, Any] = {}
    for field_name in SEMANTIC_FIELDS_016:
        value = _field_value(payload, field_name)
        if value is not None:
            result[field_name] = value
    # 0015 called this field known_invariants; accepting the name is part of
    # measuring the old baseline, not of the canonical schema.
    if "semantic_invariants" not in result and "known_invariants" in payload:
        result["semantic_invariants"] = payload["known_invariants"]
    return result


def _validate_evidence_016(evidence: Evidence016 | None, doc_id: str, documentation: str) -> bool:
    if evidence is None or evidence.doc_id in {"unknown", ""} or evidence.doc_id != doc_id:
        return False
    if evidence.quote_or_span in {"unknown", ""}:
        return False
    # A span may be a line marker; otherwise require an actual document substring.
    if evidence.quote_or_span in documentation:
        return True
    return bool(re.fullmatch(r"lines?\s*\d+(?:[-:]\d+)?", evidence.quote_or_span.strip(), re.I))


def _canonicalize_016(*, arm: str, family: PythonFamily009, payload: Mapping[str, Any] | None,
                      semantic_values: Mapping[str, Any], semantic_evidence: Mapping[str, Evidence016 | None],
                      doc_id: str, documentation: str, malformed: bool = False) -> dict[str, Any]:
    structural = structural_metadata_016(family)
    raw = payload if isinstance(payload, Mapping) else {}
    unknown = tuple(sorted(set(raw) - {
        "module", "callable", "signature", "input_type", "output_type", "allowed_imports",
        "allowed_calls", "allowed_import_members", "allowed_call_names", "deterministic",
        "allowed_attrs", "side_effects", "side_effect_policy", "return_requirements", "known_invariants",
        *SEMANTIC_FIELDS_016, "field", "value", "evidence",
    }))
    structural_values: dict[str, Any] = {}
    for field_name in ("module", "callable", "signature", "input_type", "output_type", "allowed_imports", "allowed_calls", "deterministic", "side_effects"):
        if arm == "A_free_form":
            value = raw.get(field_name)
            if field_name == "allowed_calls" and value is None:
                value = raw.get("allowed_call_names") or raw.get("allowed_import_members")
            if field_name == "side_effects" and value is None:
                value = raw.get("side_effect_policy")
            structural_values[field_name] = value
        else:
            structural_values[field_name] = _structural_field_value_016(structural, field_name)
    structural_accuracy = {
        field_name: structural_values[field_name] == _structural_field_value_016(structural, field_name)
        for field_name in ("module", "callable", "signature", "input_type", "output_type", "allowed_imports", "allowed_calls", "deterministic", "side_effects")
    }
    semantic_accuracy = {field_name: semantic_field_correct_016(family, field_name, semantic_values.get(field_name)) for field_name in SEMANTIC_FIELDS_016}
    evidence_correct = {field_name: _validate_evidence_016(semantic_evidence.get(field_name), doc_id, documentation) for field_name in SEMANTIC_FIELDS_016} if arm == "D_evidence_grounded" else {}
    unsupported = 0
    for field_name, value in semantic_values.items():
        if isinstance(value, (str, list, dict)) and ("hallucinated" in _flatten_text(value) or "undocumented_import" in _flatten_text(value)):
            unsupported += 1
    unsupported += len(unknown)
    malformed = malformed or bool(unknown)
    structural_ok = all(structural_accuracy.values())
    semantic_ok = all(semantic_accuracy.values())
    evidence_ok = all(evidence_correct.values()) if arm == "D_evidence_grounded" else True
    if malformed:
        state = "REJECTED"
    elif structural_ok and semantic_ok and evidence_ok:
        state = "COMPLETE"
    elif structural_ok and not any(semantic_accuracy.values()):
        state = "STRUCTURAL_ONLY"
    else:
        state = "PARTIAL"
    critical_values = {**structural_accuracy, "operation_summary": semantic_accuracy["operation_summary"], "semantic_invariants": semantic_accuracy["semantic_invariants"]}
    return {
        "state": state, "structural": structural.to_dict(), "structural_accuracy": structural_accuracy,
        "semantic": dict(semantic_values), "semantic_accuracy": semantic_accuracy,
        "evidence": {key: (value.to_dict() if value else None) for key, value in semantic_evidence.items()},
        "evidence_correct": evidence_correct, "critical_field_accuracy": sum(critical_values.values()) / len(critical_values),
        "complete_valid": state == "COMPLETE", "unsupported_claims": unsupported,
        "unknown_or_abstentions": sum(_flatten_text(value) == "unknown" or "unknown" in _flatten_text(value) for value in semantic_values.values()),
        "unknown_fields": list(unknown), "malformed": malformed,
    }


