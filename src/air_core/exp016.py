def semantic_ground_truth_016(family: PythonFamily009) -> dict[str, Any]:
    """Structured, deterministic ground truth kept out of every model prompt."""
    kind, variant = _family_kind_variant_016(family)
    operation = family.family_id.rsplit("-", 1)[-1]
    delimiter = ("|", "~", "^")[variant]
    factor = (3, 5, 7)[variant]
    offset = (1, 2, 4)[variant]
    separator = ("/", ":", ".")[variant]
    if kind == "shards":
        summary = f"split:{delimiter};reverse_shard_order;reverse_uppercase;join:{delimiter}"
        order = ["reverse shard order", "preserve delimiter"]
        special = ["empty shards remain representable"]
    elif kind == "numbers":
        summary = f"parse comma integers;map n*{factor}+{offset};deduplicate;sort descending;join:semicolon"
        order = ["deduplicate before descending sort", "join with semicolon"]
        special = ["whitespace around integers is accepted"]
    elif kind == "object":
        direction = "descending" if variant % 2 else "ascending"
        summary = f"parse JSON object;order keys {direction};join key=value with vertical bar"
        order = [f"keys {direction}", "join with vertical bar"]
        special = ["JSON values are rendered in their parsed representation"]
    elif kind == "mixed":
        summary = f"split final hash;rotate left {variant + 1};reverse uppercase text;append scaled number"
        order = ["split at final hash", "rotate before reverse", "append numeric suffix"]
        special = ["numeric part is transformed by multiplication and offset"]
    else:
        summary = f"run length encode consecutive characters;join groups with {separator}"
        order = ["group consecutive equal characters", "join groups in input order"]
        special = ["empty input returns empty string"]
    return {
        "operation_summary": summary,
        "preconditions": ["input is a string", "input follows the documented family format"],
        "postconditions": ["return value is a string", "transformation is deterministic"],
        "semantic_invariants": [f"operation={operation}", f"family={kind}", "same input yields same output"],
        "ordering_constraints": order,
        "special_cases": special,
        "failure_behavior": ["undocumented or invalid inputs are not silently reinterpreted"],
    }


